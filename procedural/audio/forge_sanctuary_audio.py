AMBIENT_SECONDS = 20
AMBIENT_N = AMBIENT_SECONDS * SR


def amb_day():
    """Cold, quiet, high sparse air. Wounded but legible.

    Day is the phase the player is supposed to be able to think in, so the bed is mostly *space*:
    the drone sits low and almost still, and what moves is a thin band of air well above it. The
    fifth is present and the octave barely so -- open, hollow, and not company.
    """
    n = AMBIENT_N
    out = drone(n, 130.81, [           # C3, matching VoicingFor(Day)
        (0.5,  0.30, 0.05, 0.20),     # C2  -- floor under the room, felt more than heard
        (1.0,  1.00, 0.10, 0.26),     # C3  -- root
        (1.5,  0.42, 0.15, 0.30),     # G3  -- the bare fifth
        (2.0,  0.13, 0.25, 0.34),     # C4  -- brightness 0.55: open, but not lit
    ], "day")
    # High and sparse: 2.4-6.5 kHz, gated hard so it is mostly absent. The art direction's
    # "avoid high-frequency noise everywhere" applies to the ear as much as to the eye.
    mix_into(out, air(n, "day_air", 2400.0, 6500.0,
                      [(0.05, 1.00, 0.11), (0.10, 0.62, 0.47), (0.25, 0.38, 0.81)],
                      sparsity=0.52), 0.30)
    # A very quiet mid floor keeps the silence between gusts from sounding like a dropout.
    mix_into(out, air(n, "day_floor", 180.0, 900.0,
                      [(0.05, 1.0, 0.29), (0.15, 0.5, 0.63)], sparsity=0.14), 0.045)
    return out


def amb_dusk():
    """Interpretive tension; a low pulse entering.

    Dusk is the phase the design says should feel like a decision not yet finished, so this is the
    only bed with an interval that wants to resolve and does not: a minor sixth (F3 over A2) held
    against the fifth. The pulse is a swell on the sub, at the 0.28 Hz the runtime synth uses for
    this phase, shaped so it arrives rather than switches on.
    """
    n = AMBIENT_N
    out = drone(n, 110.0, [            # A2, matching VoicingFor(Dusk)
        (1.0,  1.00, 0.05, 0.22),     # A2
        (1.5,  0.34, 0.10, 0.28),     # E3  -- brightness 0.38: the fifth pulls back
        (1.587, 0.20, 0.20, 0.40),    # F3  -- the minor sixth. The unresolved one.
        (2.0,  0.075, 0.30, 0.36),    # A3
    ], "dusk")

    # The pulse: a sub sine gated by a slow raised swell rather than a sine, so it breathes in and
    # decays out instead of wobbling symmetrically. 0.30 Hz is the nearest bin to the synth's 0.28.
    sub = osc(n, 55.0, 0.13)
    swell = [smoothstep(v) ** 1.6 for v in unipolar(osc(n, 0.30, 0.0), 0.0)]
    mix_into(out, multiply(sub, swell), 0.36)
    del sub, swell

    mix_into(out, air(n, "dusk_air", 1500.0, 5200.0,
                      [(0.05, 1.0, 0.37), (0.15, 0.7, 0.71), (0.35, 0.4, 0.19)],
                      sparsity=0.44), 0.26)
    mix_into(out, air(n, "dusk_floor", 140.0, 1100.0,
                      [(0.05, 1.0, 0.53), (0.20, 0.6, 0.07)], sparsity=0.10), 0.075)
    return out


def amb_night():
    """Darker, lower fundamental, more noise floor.

    Night drops to D2 and closes the upper partials almost off (brightness 0.16). The tremolo is the
    one thing in the whole set that moves at a speed a listener can count -- 1.15 Hz, from the synth
    -- because the design's job at night is to make an empty room feel occupied before anything is
    visible. The noise floor is the loudest it gets anywhere, and it is low, not hissy: rot, not tape.
    """
    n = AMBIENT_N
    out = drone(n, 73.42, [            # D2, matching VoicingFor(Night)
        (0.5,  0.44, 0.05, 0.18),     # D1 -- sub. Below hearing on small speakers, and that is fine.
        (1.0,  1.00, 0.10, 0.24),     # D2
        (1.5,  0.155, 0.15, 0.30),    # A2 -- the fifth, nearly shut
        (2.0,  0.05, 0.20, 0.30),     # D3
        (2.995, 0.028, 0.30, 0.44),   # A3-ish, detuned. A partial that is very slightly wrong.
    ], "night")

    # Tremolo across the whole bed, not per-partial: the room dims and returns as one thing.
    trem = unipolar(osc(n, 1.15, 0.0), 0.72)   # 0.72..1.0, the same floor the synth uses
    out = multiply(out, trem)
    del trem

    mix_into(out, air(n, "night_floor", 90.0, 1400.0,
                      [(0.05, 1.0, 0.61), (0.15, 0.7, 0.23), (0.30, 0.45, 0.89)],
                      sparsity=0.06), 0.16)
    mix_into(out, air(n, "night_air", 2100.0, 5000.0,
                      [(0.05, 1.0, 0.31), (0.20, 0.6, 0.77)], sparsity=0.68), 0.085)
    return out


def amb_dawn():
    """Warmer, the noise floor receding.

    The only bed with a third in it. docs/art/04_art_direction.md: "Warmth must be earned through
    restoration" -- dawn is where it is earned, so this is the one place a major interval is allowed,
    and it is still quiet and still ends up back where it started. The high D5 shimmer is the same
    pitch the subsystem strikes on the dawn transition, so the struck tone lands inside the bed
    rather than on top of it.
    """
    n = AMBIENT_N
    out = drone(n, 146.83, [           # D3, matching VoicingFor(Dawn)
        (0.5,  0.26, 0.05, 0.16),     # D2
        (1.0,  1.00, 0.10, 0.20),     # D3
        (1.25, 0.30, 0.15, 0.26),     # F#3 -- the third. The warmth.
        (1.5,  0.46, 0.20, 0.24),     # A3
        (2.0,  0.20, 0.25, 0.30),     # D4  -- brightness 0.82: the most open voicing in the game
        (4.0,  0.045, 0.35, 0.52),    # D5  -- shimmer; the dawn strike's own pitch
    ], "dawn")
    # The floor recedes and returns once per loop rather than vanishing: a bed that fades to nothing
    # reads as a bug in-game, where the loop restarts under a player who is still standing there.
    recede = [0.30 + 0.70 * (1.0 - smoothstep(v)) for v in unipolar(osc(n, 0.05, 0.25), 0.0)]
    floor = air(n, "dawn_floor", 120.0, 1000.0,
                [(0.05, 1.0, 0.43), (0.20, 0.55, 0.11)], sparsity=0.20)
    mix_into(out, multiply(floor, recede), 0.055)
    del floor, recede
    mix_into(out, air(n, "dawn_air", 2800.0, 7500.0,
                      [(0.05, 1.0, 0.67), (0.15, 0.8, 0.13), (0.30, 0.4, 0.41)],
                      sparsity=0.40), 0.20)
    return out


def sfx_heart_warning():
    """A low struck tone with a long decay. This is the Heart speaking.

    G3 196 Hz, the exact pitch UGloamsteadSoundscapeSubsystem::HandleHeartWarning strikes. Stretched
    inharmonic partials over a sub octave, so it reads as a large stone object being struck once
    rather than as a notification. Under the bed, not over it: the design's line is that the Heart is
    not a UI sound, and the surest way to break that is a bright attack.
    """
    n = int(2.5 * SR)
    out = struck(n, 196.0, [
        (0.5,   0.55, 2.30),   # sub octave, the body
        (1.0,   1.00, 2.20),   # G3
        (2.013, 0.34, 1.20),   # stretched octave -- the detune is the "cast object" cue
        (2.991, 0.19, 0.70),
        (4.223, 0.085, 0.38),  # inharmonic, and gone before the ear resolves it as a pitch
        (5.667, 0.035, 0.22),
    ], "heart")

    # The strike itself: a short band of noise at the onset. Without it the tone fades *in*, and a
    # struck object never does.
    burst = highpass(white_noise(n, "heart_burst"), 200.0)
    burst = lowpass(burst, 2600.0)
    decay = math.exp(-6.907755 / (0.030 * SR))
    # The burst gets the same ~1 ms ramp the pitched partials get. Filtered noise does not start at
    # zero -- its first sample is whatever the first sample of the noise was -- so without this the
    # file opens on a step of tens of LSB, which is a click on the leading edge of the one sound in
    # the game that is supposed to arrive rather than appear. The endpoint audit in main() caught
    # exactly this; the ramp is the fix, not a loosened threshold.
    attack = max(int(0.0012 * SR), 1)
    env = 1.0
    for i in range(n):
        a = env if i >= attack else env * (i / float(attack))
        out[i] += burst[i] * a * 0.20
        env *= decay
    del burst
    return fade_tail(out, 0.12)


def sfx_restoration():
    """Something remembering its purpose; rising, small, not triumphant.

    A single voice gliding a fifth upward (A3 -> E4) over about a second, with a slow attack so it
    is heard as a thing waking rather than a thing announcing. Deliberately no octave leap, no final
    accent, no third: the art direction's Restoration-State rule is that the object becomes "active,
    coherent, warm, and slightly vulnerable", and the vulnerable part is the half that a fanfare
    would erase. It ends softer than it peaks.
    """
    n = int(2.0 * SR)
    out = [0.0] * n
    f_start, f_end = 220.0, 329.63          # A3 -> E4
    glide_n = int(1.15 * SR)
    two_pi_over_sr = (2.0 * math.pi) / SR

    # Three voices: the fundamental, a fifth above it entering late, and a faint two-octave shimmer.
    # Amplitudes fall steeply so the sum is a colour, not a chord.
    for index, (ratio, amp, enter_s, decay_from) in enumerate(
            [(1.0, 1.00, 0.00, 1.25), (1.5, 0.30, 0.42, 1.35), (4.0, 0.075, 0.62, 1.15)]):
        phase = ((_seed_for(("resto", index)) >> 8) & 0xFFFF) / 65536.0 * 2.0 * math.pi
        enter = int(enter_s * SR)
        attack = max(int(0.30 * SR), 1)
        rel_start = int(decay_from * SR)
        rel_len = max(n - rel_start, 1)
        for i in range(n):
            if i < enter:
                continue
            t = min((i / float(glide_n)), 1.0)
            hz = (f_start + (f_end - f_start) * smoothstep(t)) * ratio
            phase += two_pi_over_sr * hz
            a = smoothstep((i - enter) / float(attack))
            if i >= rel_start:
                a *= (1.0 - smoothstep((i - rel_start) / float(rel_len))) ** 1.4
            out[i] += math.sin(phase) * amp * a

    # A breath of air swelling under it and gone by the end -- matter, not magic.
    breath = lowpass(highpass(white_noise(n, "resto_air"), 900.0), 4200.0)
    for i in range(n):
        t = i / float(n)
        out[i] += breath[i] * 0.09 * (smoothstep(t / 0.45) * (1.0 - smoothstep((t - 0.45) / 0.55)))
    del breath
    return fade_tail(out, 0.15)


def sfx_threat_near():
    """Dry, close, physical; no musical pitch.

    There is not one sine in this function, and that is the point: anything with a stable pitch is
    heard as a *signal*, and a threat at the edge of the lantern light must be heard as an *object*.
    So it is three irregular grains of noise whose brightness collapses -- weight shifting on grit,
    close enough to have no reverb at all. The irregular spacing is what stops it reading as a
    machine; the total absence of tail is what stops it reading as a room.
    """
    n = int(1.5 * SR)
    out = [0.0] * n

    # (start_seconds, length_seconds, hz_start, hz_end, decay_seconds, amplitude)
    grains = [
        (0.000, 0.34, 5200.0,  420.0, 0.085, 1.00),
        (0.055, 0.26, 1800.0,  180.0, 0.150, 0.62),   # the body of the same impact, lower and later
        (0.293, 0.24, 4100.0,  520.0, 0.060, 0.47),
        (0.712, 0.30, 3400.0,  380.0, 0.075, 0.55),
        (0.760, 0.22, 1500.0,  160.0, 0.130, 0.30),
    ]
    for index, (start_s, len_s, hz0, hz1, decay_s, amp) in enumerate(grains):
        start = int(start_s * SR)
        length = min(int(len_s * SR), n - start)
        if length <= 0:
            continue
        src = highpass(white_noise(length, ("threat", index)), 60.0)
        shaped = sweeping_lowpass(src, hz0, hz1)
        del src
        decay = math.exp(-6.907755 / max(decay_s * SR, 1.0))
        attack = max(int(0.0012 * SR), 1)   # ~1 ms: sharp, but not a sample-edge click
        env = 1.0
        for i in range(length):
            a = env if i >= attack else env * (i / float(attack))
            out[start + i] += shaped[i] * amp * a
            env *= decay
        del shaped

    # One pass of highpass over the sum: removes the DC a swept lowpass on noise can accumulate,
    # and takes out the low thud that would make it sound like it happened in a bigger space.
    out = highpass(out, 45.0)
    out[0] = 0.0
    return fade_tail(out, 0.08)


