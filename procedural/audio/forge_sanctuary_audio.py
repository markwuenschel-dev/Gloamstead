"""
Forge the Gloamstead sanctuary audio set, deterministically, from nothing but the standard library.

WHY THIS EXISTS
    Content/ contains zero sound assets -- not one wave, cue or MetaSound anywhere in the project.
    The game is not silent: Source/Gloamstead/Audio/GloamsteadSanctuarySynth.cpp generates a bed
    sample-by-sample, and GloamsteadSoundscapeSubsystem.cpp drives it per phase. But a runtime synth
    is the half that can ship without an artist; it is not audio *content*, it cannot be auditioned
    in the editor, it cannot be routed through a sound class, and it cannot be handed to a mixer.
    This script authors the content half -- the beds and the three moments the design says the
    player must hear -- with the same "no artist, no DAW, no dependency" constraint the texture lane
    already answered for surfaces.

WHY PURE STDLIB
    No numpy, no scipy, no soundfile. Sine tables, one-pole filters and an xorshift noise source are
    written out by hand and the RIFF is emitted through `wave`. Same reasoning as
    procedural/textures/forge_sanctuary_textures.py: a content pipeline that needs a bespoke
    environment is a content pipeline that stops working. Anything that can run the engine can run
    this.

WHY DETERMINISTIC
    Every random number here comes from SEED below through a hand-rolled xorshift, seeded by an
    explicit integer/string key -- never from `random`, whose stream is a stdlib implementation
    detail, and never from time or dict order. Two runs on the same machine produce byte-identical
    WAVs, which is what makes the generated .uasset reviewable: a diff in Content/ means somebody
    changed the *recipe*, not that the generator rolled different dice.

    Honest boundary: the only cross-machine dependency is libm's `math.sin`, which is not
    bit-specified by the C standard. The determinism claim this script prints is the one that
    matters for review -- same machine, same interpreter, byte-identical output -- and is what the
    two-directory re-run check in the task actually proves.

WHY THE LOOPS CANNOT CLICK
    Not by crossfading. A crossfade hides a seam; it does not remove one, and it smears the tail of
    the loop into its own head. Instead every looping file is built to be *mathematically periodic*
    over its exact sample length N:

      * Every pitched partial and every LFO is snapped to an integer bin k, meaning exactly k whole
        cycles fit in N samples. It is generated by walking a shared table of sin(2*pi*j/N) with
        stride k, so sample N is by construction sample 0.
      * Every noise layer is filtered *circularly*: the filter state is primed on the tail of the
        buffer for at least 24 time constants before the real pass begins, so the state at sample N
        equals the state at sample 0 to ~1e-10 -- five orders of magnitude below a 16-bit LSB.
      * Every pointwise shaping function (gates, ramps, mixes) preserves periodicity trivially.

    So x[N] == x[0] by construction, and the loop point is not a special sample. The seam audit at
    the bottom of this file is the check on that claim, not the mechanism behind it: it compares the
    wrap-around step against the distribution of the file's own interior steps and fails loudly if
    the wrap is an outlier.

WHY THIS MATERIAL
    docs/art/04_art_direction.md: "mournful, sacred, weathered, and lonely", "small warmth against
    vast coldness", "Warmth must be earned through restoration", and -- read across from the texture
    rules -- "avoid high-frequency noise everywhere", "background decay should be quieter than
    meaningful structures". So: sparse, low, slow, hollow. Bare fifths rather than triads, because a
    fifth sounds like a place and a triad sounds like a feeling. No stingers, no swells that resolve,
    no reverb tail pretending to be a cathedral.

    The pitches are not invented here. They are lifted from
    UGloamsteadSoundscapeSubsystem::VoicingFor -- Day C3 130.81, Dusk A2 110, Night D2 73.42,
    Dawn D3 146.83 -- and the two struck tones from the same file's Strike() calls (Heart G3 196,
    Dawn D5 587.33). The recorded beds and the runtime synth therefore agree on the sanctuary's
    key instead of beating against each other when both are audible.

USAGE
    python forge_sanctuary_audio.py <output-directory>

    Writes seven 16-bit PCM mono 48 kHz WAVs and prints, per file, the duration, peak, RMS, DC
    offset, loop-seam audit and SHA-256.

    The companion is import_sanctuary_audio.py, which reads this directory from GLOAM_AUDIO_WAV_DIR.
"""

import hashlib
import math
import os
import sys
import wave
from array import array

# ----------------------------------------------------------------------------------------------
# Determinism
# ----------------------------------------------------------------------------------------------

# The single root of every random number in this file. Change it and the whole set changes; leave it
# alone and the set is reproducible forever.
SEED = 0x67104D  # "gloam" -- the same root the texture forge uses, for the same reason

SR = 48000  # the project's mixer runs at 48 kHz; resampling on import is a quality loss for free

# Authoring peak. Every file is normalised to the same peak and the mix decides loudness downstream:
# a bed baked quiet cannot be made loud without noise, but a bed baked at a known peak can be made
# any level at all with a volume multiplier. -6 dBFS leaves 6 dB of headroom for the runtime synth
# to sit underneath without the sum clipping.
TARGET_PEAK_DBFS = -6.0

INT16_MAX = 32767
FULL_SCALE = 32768.0


def _int_of(k):
    """Stable integer for an arbitrary key -- ints, strings, and tuples of those."""
    if isinstance(k, str):
        v = 0
        for ch in k:
            v = ((v * 131) + ord(ch)) & 0xFFFFFFFF
        return v
    if isinstance(k, (tuple, list)):
        v = 0
        for sub in k:
            v = ((v * 131) + _int_of(sub)) & 0xFFFFFFFF
        return v
    return int(k) & 0xFFFFFFFF


def _seed_for(key):
    h = (SEED ^ _int_of(key)) & 0xFFFFFFFF
    # xorshift32 has one fixed point: zero. Anything else would be an unseeded silent failure.
    return h if h else 0x9E3779B9


def white_noise(n, key):
    """`n` samples of uniform white noise in [-1, 1), from a hand-rolled xorshift32.

    Not random.Random: this must not depend on the behaviour of a stdlib PRNG across interpreter
    versions, which is the same argument the texture forge makes for its own mixer.
    """
    state = _seed_for(key)
    out = [0.0] * n
    for i in range(n):
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        out[i] = (state / 2147483648.0) - 1.0
    return out


# ----------------------------------------------------------------------------------------------
# Exactly-periodic oscillators
# ----------------------------------------------------------------------------------------------

_TABLES = {}


def sine_table(n):
    """sin(2*pi*j/n) for j in [0, n). One table serves every partial of every file of length n."""
    t = _TABLES.get(n)
    if t is None:
        two_pi_over_n = (2.0 * math.pi) / n
        t = [math.sin(two_pi_over_n * j) for j in range(n)]
        _TABLES[n] = t
    return t


def bin_for(hz, n):
    """Nearest integer number of whole cycles of `hz` that fits in `n` samples.

    Bin resolution is SR/n -- 0.05 Hz for a 20-second loop -- so the snap is inaudible (a 0.02%
    detune at worst, far under the ~0.5% just-noticeable difference) and it is the entire reason the
    loop closes on the sample.
    """
    k = int(round(hz * n / float(SR)))
    if k < 1:
        k = 1
    if k >= n // 2:
        raise ValueError("frequency %r is at or above Nyquist for n=%d" % (hz, n))
    return k


def osc(n, hz, phase=0.0):
    """A sine of `hz` snapped to a bin, exactly periodic over n samples. `phase` is in turns.

    Generated by tiling: walking the table with stride k revisits its start after n/gcd(k, n)
    samples, so only that many values are ever computed. It is a large speedup on a 960k-sample
    buffer and, more importantly, it makes the periodicity structural rather than incidental.
    """
    table = sine_table(n)
    k = bin_for(hz, n)
    g = math.gcd(k, n)
    period = n // g
    idx = int(round(phase * n)) % n
    vals = [0.0] * period
    for i in range(period):
        vals[i] = table[idx]
        idx += k
        if idx >= n:
            idx -= n
    return vals * g if g > 1 else vals


def actual_hz(hz, n):
    """The frequency `osc` will really produce, after the bin snap. Printed, not assumed."""
    return bin_for(hz, n) * SR / float(n)


# ----------------------------------------------------------------------------------------------
# Filters
# ----------------------------------------------------------------------------------------------

def _pole(cutoff_hz):
    a = math.exp(-2.0 * math.pi * cutoff_hz / SR)
    # A pole of exactly 1.0 is an integrator, which on noise is a random walk to +/-inf. A pole of
    # exactly 0.0 is a no-op. Neither is ever what a cutoff was meant to express.
    if not (0.0 < a < 1.0):
        raise ValueError("cutoff %r Hz produced a degenerate pole %r" % (cutoff_hz, a))
    return a


PRIME_TIME_CONSTANTS = 24  # exp(-24) ~ 3.8e-11, against an int16 LSB of 3.05e-5


def circular_lowpass(x, cutoff_hz):
    """One-pole lowpass run as if `x` were an infinite loop of itself.

    The state is primed on the tail of the buffer for PRIME_TIME_CONSTANTS time constants before the
    output pass starts, so the state entering sample 0 is the state leaving sample n-1 to within
    ~1e-10. That is what keeps a filtered noise bed periodic; a filter started from zero puts a
    settling transient at the head of every loop, which is exactly the click the brief forbids.
    """
    a = _pole(cutoff_hz)
    b = 1.0 - a
    n = len(x)
    prime = min(n, int(PRIME_TIME_CONSTANTS / (1.0 - a)) + 1)
    y = 0.0
    for i in range(n - prime, n):
        y = b * x[i] + a * y
    out = [0.0] * n
    for i in range(n):
        y = b * x[i] + a * y
        out[i] = y
    return out


def circular_highpass(x, cutoff_hz):
    """Complement of the circular lowpass. Periodic for the same reason, and DC-free by definition."""
    lp = circular_lowpass(x, cutoff_hz)
    return [u - v for u, v in zip(x, lp)]


def lowpass(x, cutoff_hz, state=0.0):
    """Plain forward one-pole, for one-shots -- where starting from silence is correct, not a bug."""
    a = _pole(cutoff_hz)
    b = 1.0 - a
    y = state
    out = [0.0] * len(x)
    for i, v in enumerate(x):
        y = b * v + a * y
        out[i] = y
    return out


def highpass(x, cutoff_hz):
    lp = lowpass(x, cutoff_hz)
    return [u - v for u, v in zip(x, lp)]


def sweeping_lowpass(x, hz_start, hz_end, shape=2.0):
    """One-pole lowpass whose cutoff falls from hz_start to hz_end across the buffer.

    This is the whole identity of SFX_Threat_Near: a body of noise whose brightness collapses is
    heard as something close and physical settling, where a fixed filter is heard as a hiss.
    """
    n = len(x)
    out = [0.0] * n
    y = 0.0
    inv = 1.0 / max(n - 1, 1)
    for i, v in enumerate(x):
        t = (i * inv) ** shape
        a = _pole(hz_start + (hz_end - hz_start) * t)
        y = (1.0 - a) * v + a * y
        out[i] = y
    return out


# ----------------------------------------------------------------------------------------------
# Shaping
# ----------------------------------------------------------------------------------------------

def smoothstep(t):
    if t <= 0.0:
        return 0.0
    if t >= 1.0:
        return 1.0
    return t * t * (3.0 - 2.0 * t)


def mix_into(dst, src, gain):
    for i, v in enumerate(src):
        dst[i] += v * gain
    return dst


def multiply(a, b):
    return [u * v for u, v in zip(a, b)]


def unipolar(sig, floor=0.0):
    """Map a [-1, 1] oscillator to [floor, 1] -- an amplitude, not a waveform."""
    span = 1.0 - floor
    return [floor + span * (0.5 + 0.5 * v) for v in sig]


def gate(sig, threshold, softness):
    """Pointwise soft gate. Turns a smooth envelope into a sparse, gusting one.

    Pointwise, so it cannot break periodicity -- that is why the sparseness is applied here rather
    than by windowing the noise, which would.
    """
    out = [0.0] * len(sig)
    for i, v in enumerate(sig):
        out[i] = smoothstep((v - threshold) / softness)
    return out


def slow_field(n, specs):
    """Sum of very-low-frequency sines, normalised to [0, 1]. The weather under an ambient bed.

    Several mutually irrational-ish rates so the bed never audibly repeats before the loop does,
    which is what stops a 20-second ambience from sounding like a 20-second ambience.
    """
    acc = [0.0] * n
    total = 0.0
    for hz, amp, phase in specs:
        mix_into(acc, osc(n, hz, phase), amp)
        total += amp
    inv = 0.5 / total
    return [0.5 + v * inv for v in acc]


# ----------------------------------------------------------------------------------------------
# Voices
# ----------------------------------------------------------------------------------------------

def drone(n, root_hz, partials, key):
    """Additive bed. `partials` are (ratio, amplitude, breath_hz, breath_depth).

    Each partial breathes at its own slow rate, so the chord's internal balance drifts and the
    listener never hears a static stack. Every breath rate is bin-snapped like the partial itself.
    """
    out = [0.0] * n
    for index, (ratio, amp, breath_hz, breath_depth) in enumerate(partials):
        # Phase is deterministic per partial rather than all-zero: a stack of cosines that all start
        # at 1.0 sums to a transient at sample 0 that the loop then repeats once per pass.
        phase = ((_seed_for((key, "phase", index)) >> 8) & 0xFFFF) / 65536.0
        voice = osc(n, root_hz * ratio, phase)
        if breath_depth > 0.0:
            bphase = ((_seed_for((key, "breath", index)) >> 8) & 0xFFFF) / 65536.0
            env = unipolar(osc(n, breath_hz, bphase), 1.0 - 2.0 * breath_depth)
            voice = multiply(voice, env)
        mix_into(out, voice, amp)
    return out


def air(n, key, hp_hz, lp_hz, gate_spec, sparsity):
    """Band-limited noise with a sparse, gusting envelope. The room tone, not the drone.

    Two cascaded one-poles per side rather than one: a 6 dB/octave skirt leaves enough low rumble in
    a "high air" layer to muddy the drone, and enough top in a "floor" layer to hiss.
    """
    n_src = white_noise(n, (key, "src"))
    band = circular_highpass(circular_highpass(n_src, hp_hz), hp_hz)
    del n_src
    band = circular_lowpass(circular_lowpass(band, lp_hz), lp_hz)
    field = slow_field(n, gate_spec)
    env = gate(field, sparsity, 0.34)
    del field
    return multiply(band, env)


def struck(n, hz, partials, key, attack_s=0.004):
    """A struck tone: fast attack, per-partial exponential decay, slightly inharmonic.

    `partials` are (ratio, amplitude, decay_seconds). The ratios are deliberately NOT integers.
    A harmonic stack reads as an organ or a synth pad; a stone or a cast bell has stretched, drifting
    partials, and that inharmonicity is most of why a struck object sounds struck.
    """
    out = [0.0] * n
    attack = max(int(attack_s * SR), 1)
    two_pi_over_sr = (2.0 * math.pi) / SR
    for index, (ratio, amp, decay_s) in enumerate(partials):
        w = two_pi_over_sr * hz * ratio
        # exp() per sample is the honest way to write this and is a rounding-stable recurrence when
        # written as a constant multiply; at these lengths the cost is irrelevant.
        decay = math.exp(-6.907755 / max(decay_s * SR, 1.0))  # -60 dB over decay_s
        phase = ((_seed_for((key, index)) >> 8) & 0xFFFF) / 65536.0 * 2.0 * math.pi
        env = amp
        for i in range(n):
            a = env if i >= attack else env * (i / float(attack))
            out[i] += math.sin(phase + w * i) * a
            env *= decay
    return out


def fade_tail(sig, seconds):
    """Raised-cosine fade to exactly zero over the last `seconds`.

    A one-shot that stops mid-decay clicks on the trailing edge instead of the leading one, which is
    the failure mode nobody checks because the sound has already "finished" by then.
    """
    n = len(sig)
    m = min(int(seconds * SR), n)
    for i in range(m):
        t = i / float(m)
        sig[n - m + i] *= 0.5 * (1.0 + math.cos(math.pi * t))
    sig[n - 1] = 0.0
    return sig


