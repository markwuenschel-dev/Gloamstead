# ----------------------------------------------------------------------------------------------
# Quantisation, measurement and the failures this generator must never ship silently
# ----------------------------------------------------------------------------------------------

def quantise(sig, remove_dc):
    """Float buffer -> int16 array at TARGET_PEAK_DBFS.

    `remove_dc` is true only for the loops. Subtracting the mean from a one-shot moves its first and
    last samples off zero, which converts a clean start into a click -- the exact fault this is
    supposed to prevent. One-shots are DC-free by construction (their noise layers are highpassed
    and their envelopes end at zero) and are audited rather than corrected.
    """
    n = len(sig)
    if remove_dc:
        mean = math.fsum(sig) / n
        sig = [v - mean for v in sig]

    peak = max(max(sig), -min(sig))
    if peak <= 0.0:
        raise RuntimeError("silent buffer")
    scale = (10.0 ** (TARGET_PEAK_DBFS / 20.0)) / peak

    out = array("h", bytes(2 * n))
    for i in range(n):
        v = int(math.floor(sig[i] * scale * INT16_MAX + 0.5))
        if v > INT16_MAX:
            v = INT16_MAX
        elif v < -32768:
            v = -32768
        out[i] = v
    return out


def measure(samples):
    n = len(samples)
    peak = max(max(samples), -min(samples))
    acc = 0
    for v in samples:
        acc += v * v
    rms = math.sqrt(acc / float(n))
    dc = sum(samples) / float(n)
    return peak, rms, dc


def dbfs(linear):
    return -math.inf if linear <= 0 else 20.0 * math.log10(linear / FULL_SCALE)


def seam_audit(samples):
    """How does the wrap-around step compare with the file's own interior steps?

    Returns (wrap, max_interior, mean_interior, fraction_of_interior_steps_at_least_as_large).

    The last number is the one that carries the argument. If the loop is genuinely seamless the wrap
    is an ordinary sample-to-sample step, so a substantial share of interior steps are at least as
    big. If there is a discontinuity, that share collapses toward zero -- a seam is by definition not
    drawn from the signal's own gradient distribution. A ratio against the mean alone is not enough:
    on a near-silent bed the mean step is a fraction of an LSB and any ratio against it is noise.
    """
    n = len(samples)
    wrap = abs(samples[0] - samples[n - 1])
    biggest = 0
    total = 0
    atleast = 0
    prev = samples[0]
    for i in range(1, n):
        cur = samples[i]
        d = cur - prev
        if d < 0:
            d = -d
        if d > biggest:
            biggest = d
        total += d
        if d >= wrap:
            atleast += 1
        prev = cur
    return wrap, biggest, total / float(n - 1), atleast / float(n - 1)


# A wrap step is acceptable if it is inaudible on its own (below WRAP_ABS_LSB, ~-60 dBFS relative to
# the authored peak) OR it is an ordinary member of the interior step distribution.
WRAP_ABS_LSB = 24
WRAP_MIN_SHARE = 0.005      # at least 0.5% of interior steps must be >= the wrap step
ENDPOINT_ABS_LSB = 8        # a one-shot must start and end within this of digital silence
DC_ABS_LSB = 4


def write_wav(path, samples):
    raw = samples
    if sys.byteorder == "big":
        raw = array("h", samples)
        raw.byteswap()
    blob = raw.tobytes()
    with wave.open(path, "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(SR)
        handle.writeframes(blob)
    with open(path, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest(), os.path.getsize(path)


def main():
    if len(sys.argv) < 2:
        raise SystemExit("usage: forge_sanctuary_audio.py <output-directory>")
    out_dir = os.path.abspath(sys.argv[1])
    os.makedirs(out_dir, exist_ok=True)

    print("FORGEAUD: seed=0x%X rate=%d bits=16 channels=1 target_peak=%.1f dBFS out=%s"
          % (SEED, SR, TARGET_PEAK_DBFS, out_dir))
    print("FORGEAUD: loop length %d samples (%ds) -> frequency bin resolution %.4f Hz"
          % (AMBIENT_N, AMBIENT_SECONDS, SR / float(AMBIENT_N)))
    for hz in (73.42, 110.0, 130.81, 146.83):
        print("FORGEAUD:   %.2f Hz snaps to %.4f Hz (%+.4f%%)"
              % (hz, actual_hz(hz, AMBIENT_N), 100.0 * (actual_hz(hz, AMBIENT_N) / hz - 1.0)))

    failures = []
    for name, builder, loops in SET:
        print("FORGEAUD: building %s" % name)
        samples = quantise(builder(), remove_dc=loops)
        path = os.path.join(out_dir, name + ".wav")
        digest, nbytes = write_wav(path, samples)

        n = len(samples)
        peak, rms, dc = measure(samples)
        print("FORGEAUD: %-22s %7.3fs  %8d samples  %9d B  peak=%6d (%.2f dBFS)  "
              "rms=%9.2f (%.2f dBFS)  dc=%+7.2f"
              % (name + ".wav", n / float(SR), n, nbytes, peak, dbfs(peak), rms, dbfs(rms), dc))
        print("FORGEAUD:   %-40s sha256=%s" % (name + ".wav", digest))

        if abs(dc) > DC_ABS_LSB:
            failures.append("%s DC offset is %+.2f LSB, limit %d" % (name, dc, DC_ABS_LSB))
        if peak <= 0:
            failures.append("%s is silent" % name)

        if loops:
            wrap, biggest, mean_step, share = seam_audit(samples)
            ok = wrap <= WRAP_ABS_LSB or share >= WRAP_MIN_SHARE
            print("FORGEAUD:   loop seam: wrap step=%d  interior max=%d mean=%.2f  "
                  "share of interior steps >= wrap: %.2f%%  %s"
                  % (wrap, biggest, mean_step, 100.0 * share, "OK" if ok else "<<< SEAM"))
            if not ok:
                failures.append("%s loop seam: wrap step %d is an outlier (only %.4f%% of interior "
                                "steps are as large)" % (name, wrap, 100.0 * share))
        else:
            first, last = samples[0], samples[n - 1]
            ok = abs(first) <= ENDPOINT_ABS_LSB and abs(last) <= ENDPOINT_ABS_LSB
            print("FORGEAUD:   one-shot endpoints: first=%+d last=%+d  %s"
                  % (first, last, "OK" if ok else "<<< ENDPOINT"))
            if not ok:
                failures.append("%s does not start and end at silence (first=%d last=%d)"
                                % (name, first, last))

    if failures:
        raise RuntimeError("FORGEAUD FAILED: " + "; ".join(failures))
    print("FORGEAUD: complete, %d WAV(s) in %s" % (len(SET), out_dir))


main()
